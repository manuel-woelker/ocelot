/// Token kinds recognized by the Ocelot lexer.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TokenType {
    Can,
    Arrow,
    Cannot,
    Effect,
    Else,
    Equal,
    If,
    Identifier,
    InterpolationStart,
    String,
    StringEnd,
    StringStart,
    StringText,
    False,
    Fun,
    Native,
    Not,
    Positional,
    Return,
    True,
    Use,
    Colon,
    Comma,
    DoubleColon,
    LeftParen,
    Let,
    RightParen,
    LeftBrace,
    RightBrace,
    Semicolon,
    Test,
    Unexpected,
    EndOfFile,
}
